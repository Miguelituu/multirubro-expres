export function refreshIcons(root = document) {
  createIcons({
    icons: APP_ICONS,
    attrs: {
      'stroke-width': 1.9,
      'aria-hidden': 'true'
    },
    root
  });
}

export function iconHtml(name, size = 18, extraClass = '') {
  return `<i data-lucide="${name}" class="lucide-icon ${extraClass}" style="width:${size}px;height:${size}px" aria-hidden="true"></i>`;
}
